"""Generate private Unicode 17 text properties from checksum-pinned UCD inputs.

No network access. Keep original Unicode data and its license in third_party.
"""
from pathlib import Path
from array import array
import hashlib,json,re,argparse
root=Path(__file__).resolve().parent.parent
source=root/'third_party/unicode-17'
manifest=json.loads((source/'sources.json').read_text())
for name,identity in manifest.items():
 data=(source/name).read_bytes()
 assert len(data)==identity['bytes'] and hashlib.sha256(data).hexdigest()==identity['sha256'],name
aliases={}
for line in (source/'PropertyValueAliases.txt').read_text().splitlines():
 fields=[field.strip()for field in line.split('#')[0].split(';')]
 if len(fields)>2:
  for field in fields[1:]:aliases[fields[0],field]=fields[1]
tags=sorted({short for (kind,_),short in aliases.items()if kind=='sc'})
tag_ids={tag:i for i,tag in enumerate(tags)}
bidi=sorted({short for (kind,_),short in aliases.items()if kind=='bc'})
bidi_ids={value:i for i,value in enumerate(bidi)}
def span(value):
 fields=value.strip().split('..');return int(fields[0],16),int(fields[-1],16)+1
scripts=array('H',[tag_ids['Zzzz']])*0x110000
classes=array('H',[bidi_ids['L']])*0x110000
extensions={}
for file,kind,target in [('Scripts.txt','sc',scripts),('DerivedBidiClass.txt','bc',classes)]:
 lines=(source/file).read_text().splitlines()
 if kind=='bc':
  for line in lines:
   if '@missing:'in line:
    bounds,value=line.split('@missing:')[1].split(';');first,last=span(bounds);target[first:last]=array('H',[bidi_ids[aliases[kind,value.strip()]]])*(last-first)
 for line in lines:
  line=line.split('#')[0].strip()
  if not line:continue
  bounds,value=[v.strip()for v in line.split(';')];first,last=span(bounds)
  index=tag_ids[aliases[kind,value]]if kind=='sc'else bidi_ids[aliases[kind,value]]
  target[first:last]=array('H',[index])*(last-first)
for line in (source/'ScriptExtensions.txt').read_text().splitlines():
 line=line.split('#')[0].strip()
 if not line:continue
 bounds,value=line.split(';');first,last=span(bounds);values=tuple(sorted(value.split()))
 for point in range(first,last):extensions[point]=values
sets=[];set_ids={};ranges=[];previous=None;start=0
for point in range(0x110000):
 values=extensions.get(point,(tags[scripts[point]],))
 if values not in set_ids:set_ids[values]=len(sets);sets.append(values)
 current=(scripts[point],set_ids[values],classes[point])
 if current!=previous:
  if previous is not None:ranges.extend((start,point-1,*previous))
  previous=current;start=point
ranges.extend((start,0x10ffff,*previous))
brackets=[]
for line in (source/'BidiBrackets.txt').read_text().splitlines():
 line=line.split('#')[0].strip()
 if not line:continue
 point,pair,kind=[v.strip()for v in line.split(';')];brackets.append([int(point,16),int(pair,16),kind=='o'])
compact=lambda value:json.dumps(value,separators=(',',':'))
text='// Generated by scripts/build-unicode-text.py from Unicode 17.0.0.\n// Source hashes and Unicode License V3: third_party/unicode-17/.\n'
text+="export const UNICODE_TEXT_VERSION='17.0.0';\n"
text+='const unicodeScriptTags=Object.freeze('+compact(tags)+');\n'
text+='const unicodeBidiClasses=Object.freeze('+compact(bidi)+');\n'
text+='const unicodeScriptSets=Object.freeze('+compact(sets)+'.map(values=>Object.freeze(values)));\n'
text+='const unicodeTextRanges=new Uint32Array('+compact(ranges)+');\n'
text+='const unicodeBrackets='+compact(brackets)+'as [number,number,boolean][];\n'
text+='''const brackets=new Map(unicodeBrackets.map(([point,pair,open])=>[point,Object.freeze({pair,open})]));
export interface UnicodeTextProperties {readonly script:string;readonly extensions:readonly string[];readonly bidi:string;readonly bracket?:Readonly<{pair:number;open:boolean}>}
export function unicodeTextProperties(point:number):Readonly<UnicodeTextProperties>{
 if(!Number.isInteger(point)||point<0||point>0x10ffff)throw new Error('Invalid Unicode text property code point.');
 let low=0,high=unicodeTextRanges.length/5;
 while(low+1<high){const mid=(low+high)>>>1;if(unicodeTextRanges[mid*5]<=point)low=mid;else high=mid;}
 const at=low*5;return Object.freeze({script:unicodeScriptTags[unicodeTextRanges[at+2]],extensions:unicodeScriptSets[unicodeTextRanges[at+3]],bidi:unicodeBidiClasses[unicodeTextRanges[at+4]],bracket:brackets.get(point)});
}
'''
path=root/'src/fonts/unicode-text-data.ts'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
if args.check:assert path.read_text()==text,'Generated Unicode text properties differ.'
else:path.write_text(text)
print(f'Unicode 17: {len(tags)} script tags, {len(sets)} extension sets, {len(ranges)//5} complete property ranges, {len(brackets)} brackets; {len(text.encode())} generated bytes.')
