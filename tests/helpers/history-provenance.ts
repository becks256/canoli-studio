import {expect, type Page, type TestInfo} from '@playwright/test';
import {examplePlugin} from '../../src/plugins';
import {historyScript, historyProject, historyPng, openHistoryInspector} from './history-inspector';

/** Actual script/plugin/UI commits and native persistence, without developer globals. */
export async function historyProvenanceWorkflow(page: Page, info: TestInfo, production = false) {
  await page.goto('/');
  expect(await page.evaluate(() => 'luma' in window)).toBe(!production);
  await historyScript(page, "document.resize(400,300);const layer=document.layers.add(new PaintLayer({name:'Observed artwork',x:30,y:20}));layer.strokes.add(new PaintFill({bounds:{x:0,y:0,width:120,height:90},color:'#ff0000'}));document.selectedLayer=layer", 'Observed script ready');
  const scripted = await historyProject(page, info, 'provenance-script.luma');
  if (scripted.value.history?.version !== 4) throw Error('Missing operation provenance');
  const operation = scripted.value.history.provenance.current!;
  expect(operation.origin.surface).toBe('script');
  expect(operation.origin.executionId).toMatch(/^[0-9a-f-]{36}$/);
  expect(operation.commandTypes).toContain('layer.add');
  expect(operation.commandCount).toBeGreaterThan(1);
  expect(scripted.value.history.past).toEqual([]);
  const pixels = await historyPng(page, info, 'provenance-script.png');
  await historyScript(page, "print('No mutation')", 'Read-only script ready');
  expect((await historyProject(page, info, 'provenance-read-only.luma')).value.history).toEqual(scripted.value.history);
  await page.getByRole('button', {name: 'Delete layer (Delete)', exact: true}).click();
  const deleted = await historyProject(page, info, 'provenance-editor.luma');
  if (deleted.value.history?.version !== 4) throw Error('Missing editor provenance');
  expect(deleted.value.history.provenance.current).toMatchObject({origin: {surface: 'editor'}, commandTypes: ['layer.remove']});
  expect(deleted.value.history.provenance.current!.id).not.toBe(operation.id);
  await page.getByRole('button', {name: 'Undo (Mod+Z)', exact: true}).click();
  expect((await historyProject(page, info, 'provenance-undone.luma')).value.history).toEqual(scripted.value.history);
  expect((await historyPng(page, info, 'provenance-undone.png')).bytes).toEqual(pixels.bytes);
  let dialog = await openHistoryInspector(page);
  await dialog.getByText('Operation provenance: Isolated script', {exact: true}).click();
  await expect(dialog).toContainText('Observed at acceptance in this open document session.');
  await expect(dialog).toContainText(operation.id);
  await info.attach('provenance-observed.png', {body: await dialog.screenshot(), contentType: 'image/png'});
  await dialog.getByRole('button', {name: 'Done', exact: true}).click();
  await page.getByTestId('project-input').setInputFiles(scripted.path);
  await expect(page.getByRole('button', {name: 'Undo (Mod+Z)', exact: true})).toBeDisabled();
  dialog = await openHistoryInspector(page);
  await dialog.getByText('Operation provenance: Isolated script', {exact: true}).click();
  await expect(dialog).toContainText('Stored record: not observed in this open document session and not authenticated.');
  await expect(dialog).toContainText(operation.id);
  await info.attach('provenance-stored.png', {body: await dialog.screenshot(), contentType: 'image/png'});
  await dialog.getByRole('button', {name: 'Done', exact: true}).click();
  expect((await historyPng(page, info, 'provenance-reopened.png')).bytes).toEqual(pixels.bytes);
  await page.getByRole('button', {name: 'Plugins (Mod+Shift+L)', exact: true}).click();
  await page.getByRole('button', {name: 'Load example', exact: true}).click();
  await page.getByRole('button', {name: 'Install plugin', exact: true}).click();
  await page.getByRole('button', {name: 'Close plugins', exact: true}).click();
  const installed = await historyProject(page, info, 'provenance-inert-install.luma');
  expect(installed.value.document).toEqual(scripted.value.document);
  expect(installed.value.history).toEqual(scripted.value.history);
  await page.getByRole('button', {name: 'Plugins (Mod+Shift+L)', exact: true}).click();
  await page.getByRole('button', {name: 'Run Add guide frame', exact: true}).click();
  await expect(page.getByLabel('Plugin output')).toContainText('Finished.');
  await page.getByRole('button', {name: 'Close plugins', exact: true}).click();
  const plugin = await historyProject(page, info, 'provenance-plugin.luma');
  if (plugin.value.history?.version !== 4) throw Error('Missing plugin provenance');
  const pluginOperation = plugin.value.history.provenance.current!;
  expect(pluginOperation.origin).toMatchObject({surface: 'plugin', plugin: {id: examplePlugin.id, version: examplePlugin.version, commandId: 'frame'}});
  expect(pluginOperation.origin.executionId).not.toBe(operation.origin.executionId);
  dialog = await openHistoryInspector(page);
  await dialog.getByText('Operation provenance: Installed plugin', {exact: true}).click();
  await expect(dialog).toContainText('Observed at acceptance in this open document session.');
  await expect(dialog).toContainText('studio.utilities · 1.0.0 · frame');
  await dialog.getByRole('button', {name: 'Done', exact: true}).click();
  await page.getByRole('button', {name: 'Undo (Mod+Z)', exact: true}).click();
  expect((await historyProject(page, info, 'provenance-plugin-undone.luma')).value.history).toEqual(scripted.value.history);
}
