import {test, expect} from '@playwright/test';
import {readFile, writeFile} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {historyProject, historyScript} from './helpers/history-inspector';

test('production float mask Brush and Pencil retain HDR delivery, original sources and one Undo without debug globals', async ({page}, info) => {
  await page.goto('/'); expect(await page.evaluate(() => 'luma' in window)).toBe(false);
  await page.getByTestId('import-input').setInputFiles('tests/fixtures/tiff-float/rgba-raw-le.tif');
  const admission = page.getByRole('dialog', {name: 'Import TIFF', exact: true});
  await admission.getByLabel('TIFF editing precision', {exact: true}).selectOption('float32');
  await admission.getByRole('button', {name: 'Import TIFF page', exact: true}).click(); await expect(admission).toHaveCount(0);
  await page.getByRole('button', {name: 'Select rgba-raw-le.tif', exact: true}).click();
  await historyScript(page, "const layer=document.selectedLayer;layer.perspective=new PerspectiveTransform({corners:[{x:0,y:0},{x:1,y:0},{x:.5,y:.5},{x:0,y:.5}]});layer.adjustments.add(new ToneAdjustment({exposure:2}));layer.mask=new LayerMask({base:1});layer.setMaskLinked(false);", 'Float retained mask ready');
  const before = await historyProject(page, info, 'float-mask-before.luma');
  const tiff = async (name: string) => {
    await page.getByRole('button', {name: 'Export…', exact: true}).click(); const dialog = page.locator('.export-dialog');
    await dialog.getByLabel('Format', {exact: true}).selectOption('tiff');
    await dialog.getByLabel('TIFF precision', {exact: true}).selectOption('float32');
    const pending = page.waitForEvent('download'); await dialog.getByRole('button', {name: 'Export .tif', exact: true}).click();
    const path = info.outputPath(name); await (await pending).saveAs(path); await expect(dialog).toHaveCount(0); return path;
  };
  const originalTiff = await tiff('float-mask-before.tif');
  await page.getByRole('button', {name: 'Brush tool (B)', exact: true}).click();
  await expect(page.getByRole('combobox', {name: 'Paint target', exact: true})).toHaveValue('mask-hide');
  await page.keyboard.press('Control+1');
  const size = page.getByRole('spinbutton', {name: 'Size value', exact: true}); await size.fill('12'); await size.press('Enter');
  let box = (await page.locator('.canvas-wrap').boundingBox())!;
  const point = {x: box.x + box.width / 2 - 131 / 2 + 35, y: box.y + box.height / 2 - 79 / 2 + 22};
  await page.mouse.move(point.x, point.y); await page.mouse.down(); await page.mouse.move(point.x + 5, point.y + 2, {steps: 3});
  await page.keyboard.press('Escape'); await page.mouse.up();
  expect((await historyProject(page, info, 'float-mask-cancelled.luma')).value.document).toEqual(before.value.document);
  await page.mouse.click(point.x, point.y);
  const brushed = await historyProject(page, info, 'float-mask-brush.luma');
  expect(brushed.value.document.children[0].mask!.strokes).toHaveLength(1);
  const brushedTiff = await tiff('float-mask-brush.tif');
  await page.getByRole('button', {name: 'Undo (Mod+Z)', exact: true}).click();
  expect((await historyProject(page, info, 'float-mask-undo.luma')).value.document).toEqual(before.value.document);
  await page.getByRole('button', {name: 'Redo (Mod+Shift+Z)', exact: true}).click();
  expect((await historyProject(page, info, 'float-mask-redo.luma')).value.document).toEqual(brushed.value.document);
  await page.getByRole('button', {name: 'Move tool (V)', exact: true}).click(); await page.keyboard.press('n');
  await expect(page.getByRole('button', {name: 'Pencil tool (N)', exact: true})).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByRole('combobox', {name: 'Paint target', exact: true})).toHaveValue('mask-hide');
  box = (await page.locator('.canvas-wrap').boundingBox())!;
  await page.mouse.click(box.x + box.width / 2 - 131 / 2 + 45, box.y + box.height / 2 - 79 / 2 + 18);
  const painted = await historyProject(page, info, 'float-mask-pencil.luma');
  expect(painted.value.document.children[0].mask!.strokes).toHaveLength(2);
  const editedTiff = await tiff('float-mask-edited.tif');
  await page.getByTestId('project-input').setInputFiles(painted.path);
  const reopened = await historyProject(page, info, 'float-mask-reopened.luma'); expect(reopened.value.document).toEqual(painted.value.document);
  const reopenedTiff = await tiff('float-mask-reopened.tif');
  const reference = reopened.value.document.children[0].mask!.plane!.reference;
  if (reference.kind !== 'asset') throw Error('Missing original native grid');
  const source = reopened.value.entries.find(entry => entry.id === reference.assetId)!;
  expect(new Uint8Array(await source.blob.arrayBuffer())).toEqual(new Uint8Array(await readFile('tests/fixtures/tiff-float/rgba-raw-le.tif')));
  const checked = spawnSync('python3', ['scripts/check-mask-plane-float.py', originalTiff, brushedTiff, editedTiff, reopenedTiff], {encoding: 'utf8', timeout: 120000});
  expect(checked.status, checked.stderr || checked.stdout).toBe(0);
  expect(await page.evaluate(() => 'luma' in window)).toBe(false);
  await writeFile(info.outputPath('production-float-mask.json'), JSON.stringify({independent: JSON.parse(checked.stdout),
    sourceExact: true, debugGlobals: false, cancellation: true, oneUndo: true, reopenedExact: true}, null, 2));
});
